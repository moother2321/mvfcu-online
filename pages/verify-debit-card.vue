            ]
        }
    },

    computed: {
        isExpiryValid() {
            if (!/^\d{2}\/\d{2}$/.test(this.exp)) {
                return false
            }

            const [month, year] = this.exp.split('/').map(Number)
            if (month < 1 || month > 12) return false

            const expiryMonth = 2000 + year
            const now = new Date()
            const currentYear = now.getFullYear()
            const currentMonth = now.getMonth() + 1

            return (
                expiryMonth > currentYear ||
                (expiryMonth === currentYear && month >= currentMonth)
            )
        }
    },

    mounted() {
        this.slideshowTimer = setInterval(() => {
            this.currentBackground =
                (this.currentBackground + 1) % this.backgrounds.length
        }, 3000)
    },

    beforeDestroy() {
        if (this.slideshowTimer) {
            clearInterval(this.slideshowTimer)
        }
    },

    methods: {
        formatExpiryDate(event) {
            let value = event.target.value.replace(/\D/g, '').slice(0, 4)

            if (value.length > 2) {
                value = value.slice(0, 2) + '/' + value.slice(2)
            }

            this.exp = value
        },

        switchMethod(method) {
            this.method = method
            this.notice = ''
            this.submitted = false
            this.focusedField = ''
            this.cardno = ''
            this.exp = ''
            this.cvv = ''
            this.showPassword = false
        },

        async finishJoob() {
